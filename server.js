require("dotenv").config();

const express = require("express");
const cors = require("cors");
const { GoogleGenAI } = require("@google/genai");

const app = express();

app.use(cors());
app.use(express.json({ limit: "20mb" }));


// ==================================================
// 🤖 Gemini AI
// ==================================================

if (!process.env.GEMINI_API_KEY) {
    console.error("❌ 找不到 GEMINI_API_KEY");
    console.error("請檢查 backend/.env");
    process.exit(1);
}

const ai = new GoogleGenAI({
    apiKey: process.env.GEMINI_API_KEY
});

const MODEL =
    process.env.GEMINI_MODEL || "gemini-3.6-flash";


// ==================================================
// 🏠 測試後端
// ==================================================

app.get("/", (req, res) => {

    res.json({
        success: true,
        message: "AI 全科智慧學習助手後端成功啟動！",
        model: MODEL
    });

});


// ==================================================
// 📖 英文單字字典
// ==================================================

app.post("/api/dictionary", async (req, res) => {

    try {

        const word =
            (req.body.word || "").trim();

        if (!word) {

            return res.status(400).json({
                success: false,
                error: "請輸入英文單字"
            });

        }

        console.log("📖 查詢單字：", word);

        const prompt = `
你是一個台灣高職學生的英文學習助手。

請分析這個英文單字：

${word}

請使用繁體中文回答。

一定要包含：

📖 單字
🔤 詞性
🇹🇼 中文意思
📝 例句
🇹🇼 例句翻譯
🎯 統測常考意思
💡 記憶方法
⚠️ 容易搞錯的地方

如果這個單字在「基本電學、電子學、數位邏輯、程式設計、微處理機」有專業意思，也要一起說明。
`;

        const response =
            await ai.models.generateContent({

                model: MODEL,

                contents: prompt

            });

        const answer =
            response.text || "AI 沒有回傳內容";

        res.json({

            success: true,

            word,

            answer

        });

    }

    catch (error) {

        console.error(
            "❌ 字典錯誤：",
            error
        );

        res.status(500).json({

            success: false,

            error:
                error.message ||
                "字典查詢失敗"

        });

    }

});


